use serde::{Deserialize, Serialize};

/// WebSocket 客户端的连接生命周期状态。
///
/// 可通过客户端的连接状态查询接口获取当前快照。注册连接状态监听器时，
/// 注册操作会同步回调一次当时读取到的状态，实际状态变化也会由回调任务异步
/// 通知。若状态恰好在注册边界变化，两类回调可能重复或以非严格时序到达；
/// 调用方应将每个值视为瞬时快照，不应依赖恰好一次的通知或严格的回调顺序。
#[repr(i32)]
#[derive(Copy, Clone, Debug, Deserialize, PartialEq, Serialize, Eq)]
pub enum ConnectionStatus {
    /// 客户端处于空闲状态，当前没有连接或连接尝试。
    ///
    /// 这是客户端创建后的初始状态，也是主动断开连接完成后的状态；客户端仍可再次连接。
    Idle,

    /// 正在建立初始连接。
    ///
    /// 该状态覆盖 WebSocket 握手以及初始连接流程中由重连策略触发的额外尝试；尚不能按
    /// 已连接状态发送普通消息。
    Connecting,

    /// WebSocket 握手已经成功，连接的读写任务正在运行。
    ///
    /// 客户端只有处于该状态时才具备立即发送消息的条件。
    Connected,

    /// 客户端正在按已保存的连接目标自动重新建立连接。
    ///
    /// 该状态可在已建立的连接意外中断后立即进入，也可在
    /// [`Disconnected`](Self::Disconnected) 状态收到网络恢复通知后进入。若重连最终
    /// 成功，状态会回到 [`Connected`](Self::Connected)；若按策略尝试后仍失败，状态会
    /// 转为 [`Disconnected`](Self::Disconnected)。主动断开或关闭则会先进入
    /// [`Closing`](Self::Closing)，而不遵循上述失败路径。
    Reconnecting,

    /// 客户端正在执行主动断开或关闭流程。
    ///
    /// 此阶段可能包括取消连接尝试、发送 WebSocket 关闭帧以及停止读写任务；新的发送请求
    /// 不会被接受。
    Closing,

    /// 当前连接已经中断，并且此刻没有正在进行的重连尝试。
    ///
    /// 该状态可能由连接失败、自动重试耗尽，或未启用自动重连时的异常断开产生。客户端
    /// 本身仍可复用，可由调用方再次发起连接；保留了重连目标且启用了自动重连时，网络
    /// 恢复通知也可能重新启动连接流程。
    Disconnected,

    /// 客户端及其后台工作任务已关闭，是不可恢复的终止状态。
    ///
    /// 进入该状态后不能再次连接或发送消息；如需继续使用 WebSocket，必须创建新的客户端。
    Closed,
}
