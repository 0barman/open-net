/// 预留用于描述应用层数据分块与业务消息解码边界之间的关系。
///
/// 这里的数据块由业务层提供或接收，不是 WebSocket 协议自身的帧分片。
/// 该模式用于说明解码 PB（Protocol Buffers）或其他自定义协议前，是否需要先合并数据块。
/// 枚举本身只表达策略，不会执行分块、拼接或解码。
pub enum ChunkMode {
    /// 先按顺序拼接属于同一条业务消息的所有数据块，再执行一次协议解码。
    ///
    /// 适用于单个数据块只包含部分编码内容、无法独立解码的场景。数据块的顺序和业务消息
    /// 边界必须由使用方保证。
    ReassembleBeforeDecode,

    /// 将每个数据块分别视为一条完整的业务消息并独立解码。
    ///
    /// 此模式不会在解码前拼接相邻数据块，因此每个数据块都必须包含一条可独立解码的
    /// PB 或自定义协议消息。
    IndependentMessages,
}
